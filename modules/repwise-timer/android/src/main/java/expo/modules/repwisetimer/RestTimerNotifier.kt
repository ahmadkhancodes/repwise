package expo.modules.repwisetimer

import android.app.Notification
import android.app.NotificationChannel
import android.app.NotificationManager
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.net.Uri
import android.os.Build
import androidx.core.app.NotificationCompat
import androidx.core.app.NotificationManagerCompat

/**
 * Builds the ongoing rest-timer notification: a system-drawn count-down chronometer (no JS
 * ticks), tap opens the workout, +15 s / Skip actions once the app listens for them.
 */
object RestTimerNotifier {
  const val CHANNEL_ID = "timer-ongoing"
  const val NOTIFICATION_ID = 7301
  private const val PAUSED_TIMEOUT_MS = 2L * 60L * 60L * 1000L

  /** Android 13+: POST_NOTIFICATIONS granted and the app's notifications on. */
  fun canPost(context: Context): Boolean = NotificationManagerCompat.from(context).areNotificationsEnabled()

  fun ensureChannel(context: Context) {
    if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
    val nm = context.getSystemService(Context.NOTIFICATION_SERVICE) as? NotificationManager ?: return
    if (nm.getNotificationChannel(CHANNEL_ID) != null) return
    val channel = NotificationChannel(CHANNEL_ID, "Rest timer (ongoing)", NotificationManager.IMPORTANCE_LOW).apply {
      description = "The countdown shown while you rest between sets"
      setShowBadge(false)
      setSound(null, null)
      enableVibration(false)
      lockscreenVisibility = Notification.VISIBILITY_PUBLIC
    }
    nm.createNotificationChannel(channel)
  }

  private fun smallIcon(context: Context): Int {
    // Monochrome icon generated by the expo-notifications config plugin.
    val id = context.resources.getIdentifier("notification_icon", "drawable", context.packageName)
    return if (id != 0) id else android.R.drawable.ic_lock_idle_alarm
  }

  private fun contentIntent(context: Context, sessionId: String?): PendingIntent {
    val uri = if (!sessionId.isNullOrEmpty()) "repwise://train?sessionId=${Uri.encode(sessionId)}" else "repwise://train"
    val intent = Intent(Intent.ACTION_VIEW, Uri.parse(uri)).apply {
      setPackage(context.packageName)
      addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP)
    }
    return PendingIntent.getActivity(
      context, NOTIFICATION_ID, intent,
      PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
    )
  }

  private fun actionIntent(context: Context, action: String, requestCode: Int): PendingIntent {
    val intent = Intent(context, RestTimerActionReceiver::class.java).setAction(action)
    return PendingIntent.getBroadcast(
      context, requestCode, intent,
      PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
    )
  }

  fun build(context: Context, s: RestState, now: Long = System.currentTimeMillis()): Notification {
    ensureChannel(context)
    val builder = NotificationCompat.Builder(context, CHANNEL_ID)
      .setSmallIcon(smallIcon(context))
      .setContentTitle(s.title)
      .setContentText(s.body)
      .setSubText(s.workoutTitle)
      .setCategory(NotificationCompat.CATEGORY_STOPWATCH)
      .setVisibility(NotificationCompat.VISIBILITY_PUBLIC)
      .setPriority(NotificationCompat.PRIORITY_LOW)
      .setOngoing(true)
      .setOnlyAlertOnce(true)
      .setSilent(true)
      .setContentIntent(contentIntent(context, s.sessionId))
      .setForegroundServiceBehavior(NotificationCompat.FOREGROUND_SERVICE_IMMEDIATE)

    if (s.paused) {
      // A paused rest has no end time: still remove it eventually if the app is killed meanwhile.
      builder.setUsesChronometer(false).setShowWhen(false).setTimeoutAfter(PAUSED_TIMEOUT_MS)
    } else {
      builder.setUsesChronometer(true)
        .setChronometerCountDown(true)
        .setWhen(s.endsAt)
        .setShowWhen(true)
        // Remove itself a little after rest ends if nothing else gets to cancel it.
        .setTimeoutAfter(maxOf(1_000L, s.endsAt - now + 60_000L))
    }
    if (RestTimerStore.actionsEnabled(context)) {
      builder.addAction(0, "+15 s", actionIntent(context, RestTimerActions.ACTION_ADD_15, NOTIFICATION_ID + 1))
      builder.addAction(0, "Skip", actionIntent(context, RestTimerActions.ACTION_SKIP, NOTIFICATION_ID + 2))
    }
    return builder.build()
  }

  /** Plain (non-service) post. Never throws. */
  fun post(context: Context, s: RestState): Boolean {
    if (!canPost(context)) return false
    return try {
      NotificationManagerCompat.from(context).notify(NOTIFICATION_ID, build(context, s))
      true
    } catch (e: SecurityException) {
      false
    } catch (e: RuntimeException) {
      false
    }
  }

  fun cancel(context: Context) {
    try {
      NotificationManagerCompat.from(context).cancel(NOTIFICATION_ID)
    } catch (e: RuntimeException) {
      // nothing to cancel
    }
  }
}
