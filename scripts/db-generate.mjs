// Runs drizzle-kit generate, then inlines the SQL files into src/db/migrations/migrations.ts so
// Metro needs no .sql loader (no extra babel plugin). Usage: npm run db:generate [-- --name=x]
import { execFileSync } from 'node:child_process';
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(process.cwd(), 'src/db/migrations');
execFileSync('npx', ['drizzle-kit', 'generate', ...process.argv.slice(2)], { stdio: 'inherit' });

const journal = JSON.parse(readFileSync(join(dir, 'meta/_journal.json'), 'utf8'));
const lines = [
  '// GENERATED by scripts/db-generate.mjs from drizzle-kit output. Do not edit by hand.',
  `const journal = ${JSON.stringify(journal, null, 2)};`,
  '',
  'export const migrations = {',
  '  journal,',
  '  migrations: {',
];
for (const e of journal.entries) {
  const sql = readFileSync(join(dir, `${e.tag}.sql`), 'utf8');
  lines.push(`    m${String(e.idx).padStart(4, '0')}: ${JSON.stringify(sql)},`);
}
lines.push('  },', '};', '', 'export default migrations;', '');
writeFileSync(join(dir, 'migrations.ts'), lines.join('\n'));
// drizzle-kit's migrations.js imports .sql files, which Metro cannot load without a plugin.
rmSync(join(dir, 'migrations.js'), { force: true });
console.log(`inlined ${journal.entries.length} migration(s) into src/db/migrations/migrations.ts`);
