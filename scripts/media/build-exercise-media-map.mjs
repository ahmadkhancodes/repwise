#!/usr/bin/env node
/**
 * Builds packages/content/media/exercise-media-map.json (+ exercises-with-media.json) from the reviewed decisions in
 * scripts/media/exercise-match-decisions.json and the free-exercise-db dataset.
 *
 *   node scripts/media/build-exercise-media-map.mjs <path/to/free-exercise-db/dist/exercises.json> [--check-urls]
 *
 * The dataset file must be the one at DATASET_COMMIT (fetch it from RAW_BASE + 'dist/exercises.json').
 * Every source URL is pinned to that commit, so the proof never moves. --check-urls also HEADs each
 * image (slow; ~360 requests). The script fails if a decision names a missing source or a source
 * without exactly two images, or if any Repwise exercise has no decision.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const DATASET_REPO = 'https://github.com/yuhonas/free-exercise-db';
export const DATASET_COMMIT = 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
export const RAW_BASE = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${DATASET_COMMIT}/`;

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const datasetPath = process.argv[2];
if (!datasetPath) {
  console.error('usage: build-exercise-media-map.mjs <dataset exercises.json> [--check-urls]');
  process.exit(2);
}

const ours = JSON.parse(readFileSync(join(root, 'packages/content/exercises.json'), 'utf8'));
const dataset = new Map(JSON.parse(readFileSync(datasetPath, 'utf8')).map((e) => [e.id, e]));
const { decisions } = JSON.parse(readFileSync(join(here, 'exercise-match-decisions.json'), 'utf8'));

const errors = [];
const exercises = {};
const unmatched = [];
for (const ex of ours) {
  const d = decisions[ex.id];
  if (!d) {
    errors.push(`${ex.id}: no decision`);
    continue;
  }
  if (d.source === null) {
    unmatched.push(ex.id);
    continue;
  }
  const src = dataset.get(d.source);
  if (!src) errors.push(`${ex.id}: source ${d.source} not in dataset`);
  else if (src.images?.length !== 2) errors.push(`${ex.id}: source ${d.source} has ${src.images?.length ?? 0} images`);
  else if (d.confidence !== 'high' && d.confidence !== 'medium') errors.push(`${ex.id}: bad confidence`);
  else {
    exercises[ex.id] = {
      sourceId: src.id,
      sourceName: src.name,
      confidence: d.confidence,
      ...(d.note ? { note: d.note } : {}),
      start: { url: RAW_BASE + 'exercises/' + src.images[0], publicId: `repwise/exercises/${ex.id}` },
      end: { url: RAW_BASE + 'exercises/' + src.images[1], publicId: `repwise/exercises/${ex.id}-end` },
    };
  }
}
for (const id of Object.keys(decisions)) {
  if (!ours.some((e) => e.id === id)) errors.push(`${id}: decision for an unknown exercise`);
}

if (process.argv.includes('--check-urls')) {
  for (const [id, m] of Object.entries(exercises)) {
    for (const u of [m.start.url, m.end.url]) {
      const r = await fetch(u, { method: 'HEAD' });
      if (!r.ok) errors.push(`${id}: ${u} → HTTP ${r.status}`);
    }
  }
}

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const out = {
  $comment: 'Generated by scripts/media/build-exercise-media-map.mjs from scripts/media/exercise-match-decisions.json. Do not edit by hand.',
  source: {
    name: 'free-exercise-db',
    repo: DATASET_REPO,
    commit: DATASET_COMMIT,
    licence: 'Unlicense',
    licenceUrl: `${DATASET_REPO}/blob/${DATASET_COMMIT}/LICENSE.md`,
    licenceRawUrl: `${RAW_BASE}LICENSE.md`,
    images: 'Two JPEG frames per exercise (start, end), 850 x 567 px.',
  },
  counts: {
    exercises: ours.length,
    matched: Object.keys(exercises).length,
    high: Object.values(exercises).filter((m) => m.confidence === 'high').length,
    medium: Object.values(exercises).filter((m) => m.confidence === 'medium').length,
    unmatched: unmatched.length,
  },
  unmatched,
  exercises,
};
mkdirSync(join(root, 'packages/content/media'), { recursive: true });
writeFileSync(join(root, 'packages/content/media/exercise-media-map.json'), JSON.stringify(out, null, 2) + '\n');
// Compact list the app bundles (via exerciseHasMedia): only these exercises ever request media.
writeFileSync(
  join(root, 'packages/content/media/exercises-with-media.json'),
  JSON.stringify(
    {
      $comment: 'Generated by scripts/media/build-exercise-media-map.mjs. Exercises with a licensed demo (start + end frame) at repwise/exercises/<id>[-end].',
      exercises: Object.keys(exercises).sort(),
    },
    null,
    2,
  ) + '\n',
);
console.log(`wrote exercise-media-map.json: ${out.counts.matched} matched (${out.counts.high} high, ${out.counts.medium} medium), ${out.counts.unmatched} unmatched`);
