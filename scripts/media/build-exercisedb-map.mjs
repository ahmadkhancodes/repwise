#!/usr/bin/env node
/**
 * Builds packages/content/exercise_media.json: our engine exercise id → ExerciseDB V1 id
 * (licensed, D-EXDB-LICENCE), from packages/content/exercisedb_v1.json.
 *
 *   node scripts/media/build-exercisedb-map.mjs            # write the map
 *   node scripts/media/build-exercisedb-map.mjs --review   # also print one line per exercise
 *
 * How a match is chosen:
 *  1. scripts/media/exercisedb-overrides.json wins: a hand-checked ExerciseDB id, or null when
 *     no V1 exercise shows the movement honestly (the app then shows our muscle map).
 *  2. Otherwise a name score: token overlap between our name + aliases and the V1 name, a bonus
 *     when the V1 equipment matches ours, a penalty for variant noise ("v. 2", "female", props
 *     we do not use). A candidate WITH a GIF beats one without at the same score (owner, 22 Nov).
 *     Below MIN_SCORE the exercise stays unmatched rather than guessed.
 *
 * Deterministic: same inputs → byte-identical output (sorted keys, ties broken by V1 id).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const review = process.argv.includes('--review');

const ours = JSON.parse(readFileSync(join(root, 'packages/content/exercises.json'), 'utf8'));
const v1 = JSON.parse(readFileSync(join(root, 'packages/content/exercisedb_v1.json'), 'utf8'));
const overrides = JSON.parse(readFileSync(join(here, 'exercisedb-overrides.json'), 'utf8')).overrides;
const byId = new Map(v1.map((e) => [e.exerciseId, e]));

export const MIN_SCORE = 0.5;

const SYNONYMS = {
  db: 'dumbbell',
  dumbbells: 'dumbbell',
  bb: 'barbell',
  kb: 'kettlebell',
  smith: 'smith',
  ez: 'ez',
  pushup: 'push',
  pullup: 'pull',
  chinup: 'chin',
  situp: 'sit',
  squats: 'squat',
  lunges: 'lunge',
  curls: 'curl',
  raises: 'raise',
  rows: 'row',
  presses: 'press',
  flyes: 'fly',
  flye: 'fly',
  triceps: 'triceps',
  tricep: 'triceps',
  bicep: 'biceps',
  curtsey: 'curtsy',
  banded: 'band',
  bands: 'band',
  pec: 'pec',
  deck: 'deck',
};
const STOP = new Set(['the', 'a', 'with', 'on', 'to', 'and', 'of', 'up', 'machine', 'v', '2', '3', 'version']);
const NOISE = /\b(v\. ?\d|female|male|version|pov|with support|on knees|holding)\b/;
const EQUIP = {
  barbell: ['barbell', 'olympic barbell'],
  dumbbell: ['dumbbell'],
  kettlebell: ['kettlebell'],
  cable: ['cable', 'rope'],
  band: ['resistance band'],
  smith_machine: ['smith machine'],
  machine: ['leverage machine', 'sled machine', 'assisted'],
  ez_bar: ['EZ bar'],
  trap_bar: ['trap bar'],
  bodyweight: ['bodyweight'],
  none: ['bodyweight'],
  pull_up_bar: ['bodyweight', 'assisted', 'weighted'],
  suspension: ['suspension trainer'],
  stability_ball: ['stability ball'],
};

function tokens(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9 ]+/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => SYNONYMS[w] ?? w)
    .filter((w) => !STOP.has(w));
}

function score(names, equipment, cand) {
  const ct = new Set(tokens(cand.name));
  let best = 0;
  for (const n of names) {
    const nt = new Set(tokens(n));
    const common = [...nt].filter((w) => ct.has(w)).length;
    const union = new Set([...nt, ...ct]).size;
    if (union) best = Math.max(best, common / union);
  }
  const wanted = equipment.flatMap((e) => EQUIP[e] ?? []);
  if (cand.equipments.some((e) => wanted.includes(e))) best += 0.1;
  if (NOISE.test(cand.name)) best -= 0.1;
  return best;
}

const map = {};
const lines = [];
let withGif = 0;
for (const ex of ours) {
  let pick = null;
  let how = 'auto';
  if (Object.hasOwn(overrides, ex.id)) {
    pick = overrides[ex.id];
    how = 'hand';
    if (pick !== null && !byId.has(pick)) throw new Error(`override ${ex.id} → unknown V1 id ${pick}`);
  } else {
    const names = [ex.name, ...(ex.aliases ?? [])];
    let top = null;
    for (const c of v1) {
      const s = score(names, ex.equipment ?? [], c) + (c.gifUrl ? 0.001 : 0);
      if (!top || s > top.s || (s === top.s && c.exerciseId < top.c.exerciseId)) top = { s, c };
    }
    if (top && top.s >= MIN_SCORE) pick = top.c.exerciseId;
  }
  map[ex.id] = pick;
  const c = pick ? byId.get(pick) : null;
  if (c?.gifUrl) withGif++;
  lines.push(`${how} ${ex.id} → ${c ? `${c.name} [${c.equipments.join(',')}]${c.gifUrl ? '' : ' NOGIF'}` : '—'}`);
}

const sorted = Object.fromEntries(Object.keys(map).sort().map((k) => [k, map[k]]));
const out = {
  $comment:
    'Generated by scripts/media/build-exercisedb-map.mjs (overrides: scripts/media/exercisedb-overrides.json). Engine exercise id → ExerciseDB V1 id (null: no honest match, the app shows the muscle map). Do not edit by hand.',
  source: 'ExerciseDB V1 (licensed, D-EXDB-LICENCE)',
  exercises: sorted,
};
writeFileSync(join(root, 'packages/content/exercise_media.json'), `${JSON.stringify(out, null, 2)}\n`);
if (review) console.log(lines.join('\n'));
console.log(`mapped ${Object.values(map).filter(Boolean).length}/${ours.length}, with GIF ${withGif}`);
